  /// Busca um texto para uma chave e idioma, com fallback para pt-BR.
  static String text(String key, String languageCode) {
    final langMap = uiTexts[languageCode];
    if (langMap != null && langMap.containsKey(key)) {
      return langMap[key]!;
    }
    // Fallback para pt-BR
    return uiTexts['pt-BR']![key] ?? key;
  }
